import { test, expect, type Page } from 'playwright/test'
import { readFile } from 'node:fs/promises'

async function openTutorial(page: Page, title: string) {
  await page.locator('article').filter({ has: page.getByRole('heading', { name: title, exact: true }) })
    .getByRole('button', { name: 'Abrir tutorial' }).click()
  await expect(page.locator('canvas')).toBeVisible()
  await expect(page.locator('.scene-status')).toContainText('Explore o resultado')
}
async function nextFold(page: Page) {
  await page.getByRole('button', { name: 'Próximo', exact: true }).click()
  await expect(page.locator('.scene-status')).toContainText(/faces que vão se mover|Acompanhe a dobra|Explore o resultado/)
  await expect(page.locator('.scene-status')).toContainText('Explore o resultado')
}

test('library defers the engine and editor; highlight, replay, math and finish work', async ({ page }, testInfo) => {
  const engineRequests: string[] = [], errors: string[] = []
  page.on('request', (request) => { if (/OrigamiScene-.*\.js/.test(request.url())) engineRequests.push(request.url()) })
  page.on('pageerror', (error) => errors.push(error.message))
  await page.goto('./')
  await expect(page.getByRole('heading', { name: 'Escolha um tutorial' })).toBeVisible()
  expect(engineRequests).toEqual([])
  await expect(page.locator('article')).toHaveCount(4)
  await openTutorial(page, 'Cachorro de origami')
  expect(engineRequests.length).toBeGreaterThan(0)
  await page.getByRole('button', { name: 'Próximo', exact: true }).click()
  await expect(page.locator('.scene-status')).toContainText('faces que vão se mover')
  await page.screenshot({ path: testInfo.outputPath('faces-before-fold.png'), fullPage: true })
  await expect(page.locator('.scene-status')).toContainText('Explore o resultado')
  await page.getByRole('button', { name: 'Repetir', exact: true }).click()
  await expect(page.locator('.scene-status')).toContainText('faces que vão se mover')
  await page.getByRole('button', { name: 'Modo Matemática' }).click()
  await expect(page.locator('.math-label')).toContainText('Eixo de reflexão')
  await page.getByRole('button', { name: '2×', exact: true }).click()
  await expect(page.locator('.scene-status')).toContainText('Explore o resultado')
  await nextFold(page); await nextFold(page); await nextFold(page)
  await expect(page.getByRole('heading', { name: 'Pinte e desenhe o rosto' })).toBeVisible()
  await page.screenshot({ path: testInfo.outputPath('dog-finished.png'), fullPage: true })
  await page.getByRole('button', { name: 'Voltar', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Abaixe a orelha direita' })).toBeVisible()
  await page.getByRole('button', { name: 'Biblioteca', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Escolha um tutorial' })).toBeVisible()
  expect(errors).toEqual([])
})

